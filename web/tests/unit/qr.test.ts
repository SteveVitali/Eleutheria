// --- The reader: unmask + zigzag traversal over a matrix --------------------
// Re-implements the ISO read order so the matrix itself — not the encoder's
// internals — is what gets checked.

function isFunctionModule(size: number, r: number, c: number): boolean {
  const n = size;
  // Finders + separators: the top-left's separator runs down/right; the other
  // two run up/left, so each clip is 8×8 on the grid side.
  if (r <= 7 && c <= 7) return true; // top-left
  if (r <= 7 && c >= n - 8) return true; // top-right
  if (r >= n - 8 && c <= 7) return true; // bottom-left
  if (r === 6 || c === 6) return true; // timing
  // Alignment patterns — centres from the version's table row.
  const centers: Record<number, number[]> = {
    21: [], 25: [6, 18], 29: [6, 22], 33: [6, 26], 37: [6, 30], 41: [6, 34],
    45: [6, 22, 38], 49: [6, 26, 46], 53: [6, 28, 50], 57: [6, 30, 54],
  };
  const cs = centers[n] ?? [];
  for (let i = 0; i < cs.length; i++) {
    for (let j = 0; j < cs.length; j++) {
      const corner = (i === 0 && j === 0) || (i === 0 && j === cs.length - 1) || (i === cs.length - 1 && j === 0);
      if (!corner && Math.abs(r - cs[i]!) <= 2 && Math.abs(c - cs[j]!) <= 2) return true;
    }
  }
  // Format copy 1 (row 8 cols 0–8, col 8 rows 0–8 incl. crossing).
  if (r === 8 && c <= 8) return true;
  if (c === 8 && r <= 8) return true;
  // Format copy 2 + dark module.
  if (r === 8 && c >= n - 8) return true;
  if (c === 8 && r >= n - 8) return true;
  // Version info for v ≥ 7.
  const version = (n - 17) / 4;
  if (version >= 7 && ((r < 6 && c >= n - 11 && c <= n - 9) || (c < 6 && r >= n - 11 && r <= n - 9))) {
    return true;
  }
  return false;
}

const MASK = (m: number) => {
  const fns: ((r: number, c: number) => boolean)[] = [
    (r, c) => (r + c) % 2 === 0,
    (r) => r % 2 === 0,
    (_r, c) => c % 3 === 0,
    (r, c) => (r + c) % 3 === 0,
    (r, c) => (Math.floor(r / 2) + Math.floor(c / 3)) % 2 === 0,
    (r, c) => ((r * c) % 2) + ((r * c) % 3) === 0,
    (r, c) => (((r * c) % 2) + ((r * c) % 3)) % 2 === 0,
    (r, c) => (((r + c) % 2) + ((r * c) % 3)) % 2 === 0,
  ];
  return fns[m]!;
};

function readDataBytes(m: { size: number; modules: boolean[] }, mask: number): number[] {
  const n = m.size;
  const at = (r: number, c: number) => m.modules[r * n + c]!;
  const bits: number[] = [];
  let up = true;
  for (let c = n - 1; c >= 1; c -= 2) {
    if (c === 6) c = 5; // the timing column — mutates the counter like the spec
    for (let i = 0; i < n; i++) {
      const r = up ? n - 1 - i : i;
      for (const cc of [c, c - 1]) {
        if (isFunctionModule(n, r, cc)) continue;
        bits.push((at(r, cc) !== MASK(mask)(r, cc)) ? 1 : 0);
      }
    }
    up = !up;
  }
  const bytes: number[] = [];
  for (let i = 0; i + 8 <= bits.length; i += 8) {
    bytes.push(bits.slice(i, i + 8).reduce((a, b) => (a << 1) | b, 0));
  }
  return bytes;
}

const hex = (bytes: number[]) => bytes.map((b) => b.toString(16).padStart(2, "0")).join(" ");

