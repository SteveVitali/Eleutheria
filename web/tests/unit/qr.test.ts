// The ISO format words for EC level M (the canonical 15-bit table).
const FORMAT_M = [
  "101010000010010", "101000100100101", "101111001111100", "101101101001011",
  "100010111111001", "100000011001110", "100111110010111", "100101010100000",
];

function formatCells(m: { size: number; modules: boolean[] }): { copy1: string; copy2: string } {
  const n = m.size;
  const at = (r: number, c: number) => (m.modules[r * n + c] ? "1" : "0");
  const c1 =
    [0, 1, 2, 3, 4, 5].map((c) => at(8, c)).join("") +
    at(8, 7) + at(8, 8) + at(7, 8) +
    [5, 4, 3, 2, 1, 0].map((r) => at(r, 8)).join("");
  const c2 =
    [0, 1, 2, 3, 4, 5, 6, 7].map((i) => at(8, n - 1 - i)).join("") +
    [8, 9, 10, 11, 12, 13, 14].map((i) => at(n - 15 + i, 8)).join("");
  // copy1 is stored MSB-first in the ISO winding order → the read order above
  // (bit 14 → bit 0); copy2's traversal reads bit 0 → bit 14.
  return { copy1: c1, copy2: c2 };
}

const rows = (golden: string) => golden.split("/").map((r) => [...r].map((ch) => ch === "1"));

describe("qrEncode — byte-mode, EC level M", () => {
  it("encodes the reference codeword stream (single block, v1)", () => {
    const m = qrEncode("HELLO", { mask: 0 });
    expect(m.version).toBe(1);
    expect(m.size).toBe(21);
    expect(hex(readDataBytes(m, 0))).toBe(HELLO_V1_STREAM);
  });

  it("interleaves the reference stream (two blocks, v4)", () => {
    const m = qrEncode(URL_V4, { mask: 2 });
    expect(m.version).toBe(4);
    expect(hex(readDataBytes(m, 2))).toBe(URL_V4_STREAM);
  });

  it("writes the spec format word for every mask, in both copies", () => {
    for (let mask = 0; mask < 8; mask++) {
      const m = qrEncode("HELLO", { mask });
      const { copy1, copy2 } = formatCells(m);
      // copy1 reads the word MSB-first; copy2's traversal reads LSB-first.
      expect(copy1).toBe(FORMAT_M[mask]);
      expect(copy2).toBe([...FORMAT_M[mask]!].reverse().join(""));
    }
  });

  it("picks the smallest fitting version and fails closed beyond capacity", () => {
    expect(qrEncode("A").version).toBe(1);
    expect(qrEncode(PERMALINK).version).toBe(8);
    expect(qrCapacityBytes(10)).toBe(213);
    expect(qrEncode("x".repeat(213)).version).toBe(10);
    expect(() => qrEncode("x".repeat(214))).toThrow(RangeError);
  });

  it("counts payload in bytes (a multi-byte char takes real capacity)", () => {
    // 5 bytes — fits v1 (14-byte byte-mode capacity).
    expect(qrEncode("héllö").version).toBe(1);
    // 15 bytes — over v1.
    expect(qrEncode("héllö wörld!").version).toBe(2);
  });

  it("auto-selection returns a real masked symbol (one of the eight)", () => {
    const auto = qrEncode(URL_V4);
    const options = Array.from({ length: QR_MASK_COUNT }, (_, m) => qrEncode(URL_V4, { mask: m }));
    expect(options.some((o) => o.modules.every((b, i) => b === auto.modules[i]))).toBe(true);
  });

  it("is deterministic — the same URL always yields the same modules", () => {
    expect(qrEncode(PERMALINK).modules).toEqual(qrEncode(PERMALINK).modules);
  });

  it("matches the decoder-verified goldens", () => {
    const hello = qrEncode("HELLO", { mask: 3 });
    expect(hello.version).toBe(1);
    expect(hello.modules).toEqual(rows(GOLDEN_HELLO_V1_M3).flat());
    const url = qrEncode(PERMALINK, { mask: 0 });
    expect(url.version).toBe(8);
    expect(url.modules).toEqual(rows(GOLDEN_URL_V8_M0).flat());
  });

  it("draws finders, timing, and the dark module where the spec puts them", () => {
    const m = qrEncode("HELLO", { mask: 0 });
    const at = (r: number, c: number) => m.modules[r * m.size + c]!;
    // Finder corners are dark 7×7 rings.
    for (const [fr, fc] of [[0, 0], [0, 14], [14, 0]] as const) {
      expect(at(fr, fc)).toBe(true);
      expect(at(fr + 3, fc + 3)).toBe(true);
      expect(at(fr + 1, fc + 1)).toBe(false); // the light ring
    }
    // Timing alternates from a dark start.
    expect(at(6, 8)).toBe(true);
    expect(at(6, 9)).toBe(false);
    // The dark module.
    expect(at(13, 8)).toBe(true);
    expect(QR_EC_LEVEL).toBe("M");
  });
});

describe("qrPathData — the static SVG the brief prints", () => {
  it("produces a viewBox covering the quiet zone and one rect per dark module run", () => {
    const m = qrEncode("HELLO");
    const { viewBox, d } = qrPathData(m);
    expect(viewBox).toBe(m.size + 8); // 4-module quiet zone each side
    // Every path command is M<x> <y>h<w>v1h<-w>z — the total painted area is
    // exactly the dark-module count.
    const painted = [...d.matchAll(/M(\d+) (\d+)h(\d+)v1h-\d+z/g)].reduce(
      (a, cmd) => a + Number(cmd[3]),
      0,
    );
    expect(painted).toBe(m.modules.filter(Boolean).length);
    // Every painted module stays inside the symbol (the quiet zone is empty).
    for (const cmd of d.matchAll(/M(\d+) (\d+)h(\d+)v1h-\d+z/g)) {
      expect(Number(cmd[1])).toBeGreaterThanOrEqual(4);
      expect(Number(cmd[1]) + Number(cmd[3])).toBeLessThanOrEqual(4 + m.size);
      expect(Number(cmd[2])).toBeGreaterThanOrEqual(4);
      expect(Number(cmd[2])).toBeLessThan(4 + m.size);
    }
  });
});
