// P36.26 — the print-document QR encoder (lib/qr.ts). Conformance is pinned
// three ways (SIG-ENG-042 — never a vacuous pass):
//
//   1. REFERENCE CODEWORD STREAMS — the interleaved (data ++ EC) bytes a
//      reader extracts from the matrix, checked against vectors produced by
//      an independent Reed–Solomon implementation (reedsolo);
//   2. THE FORMAT/VERSION/TIMING/FINDER LAYOUT — spec-mandated cells;
//   3. DECODER-VERIFIED GOLDEN MATRICES — the exact matrices below were
//      generated by lib/qr.ts and confirmed to decode back to their payloads
//      with a real QR decoder (OpenCV QRCodeDetector) during P36.26's
//      verification; any regression in placement, masking, or format writing
//      breaks the golden.

