"""D-P34.13-1 (P34.40) — the generated ``conf/`` fragments nginx wires dark.

``ops/web/nginx.conf`` includes ``/mnt/sig-web/conf/chrome_*.conf`` and
``/mnt/sig-web/conf/terms_*.conf`` — the same conf/-fragment mechanism the
withdrawal (``withdrawn_*.conf``) and renamed-identifier (``renamed_*.conf``)
barriers already use. Absent fragments are no-ops, so the P34.40 ``sig-web``
roll (L1) changes zero allow-listed responses; a fragment takes effect when
it lands under the bucket's ``conf/`` prefix (a publish-path write, owned
downstream of D-R10-PUBLISH-1) AND the running nginx reloads or rolls — the
include is read at start.

This module generates the two fragments deterministically:

* ``chrome_routes.conf`` — ``error_page 403``/``410`` onto the branded
  static assets (P34.13 ships ``/403.html`` + ``/410.html`` in the
  allow-listed build) and the ``/task/`` 403 → 404 map per G1's route table
  (the bare prefix is denied; ``/task/<handle>/`` stays allow-listed).
* ``terms_redirect.conf`` — a true 302 for ``/terms`` (and ``/terms/``) to
  the API's acceptable-use document — never a meta-refresh (WCAG 2.2.1,
  N-7). The API serves ``/terms`` at its own root (SIG-API-013), off the
  canonical origin's ``/v1/*`` rule, so the target is the API base URL the
  operator supplies (``SIG_API_BASE_URL``, the same value the web build
  bakes via ``publicApiBaseUrl()``).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

#: The allow-listed branded pages (P34.13 — flat copies exist for exactly
#: this error_page mapping).
CHROME_ERROR_PAGES = {403: "/403.html", 410: "/410.html"}

#: The §6.3 sig-web provenance pair's value grammar — the release label is
#: the descriptor's ``sig-YYYY-MM-DD.N`` and the publication id is
#: ``p-<64hex>``; nothing else may reach generated nginx (a quote/newline
#: would smuggle directives).
_LABEL_RE = re.compile(r"^sig-\d{4}-\d{2}-\d{2}\.\d+$")
_PUB_RE = re.compile(r"^p-[0-9a-f]{64}$")

#: The bare /task/ prefix is denied (G1 route table; the retired fixture
#: intake namespace under it stays refused by ops/public_routes.toml).
TASK_PREFIX_ROUTE = "/task/"


def render_chrome_conf() -> str:
    """``conf/chrome_routes.conf`` — branded error pages + /task/ → 404."""
    return (
        "# D-P34.13-1 / P34.40 — generated by `sig-ops web-conf`; do not\n"
        "# hand-edit. Lands under <bucket>/conf/ (a protected prefix).\n"
        "# Branded error pages (the assets ship in the allow-listed build):\n"
        + "".join(f"error_page {code} {page};\n" for code, page in CHROME_ERROR_PAGES.items())
        + "\n"
        "# G1 route table: the bare /task/ prefix is denied — answer a plain\n"
        "# 404 (branded via error_page 404 above in nginx.conf), never the\n"
        "# bucket's 403. /task/<handle>/ stays routed.\n"
        f"location = {TASK_PREFIX_ROUTE} {{ return 404; }}\n"
    )


def render_terms_conf(api_base: str) -> str:
    """``conf/terms_redirect.conf`` — a true 302 to the API terms document."""
    base = api_base.rstrip("/")
    if not base.startswith("http://") and not base.startswith("https://"):
        raise ValueError(f"--api-base must be an absolute http(s) URL, got {api_base!r}")
    return (
        "# D-P34.13-1 / P34.40 — generated by `sig-ops web-conf --api-base`;\n"
        "# do not hand-edit. A real 302 — never a meta-refresh that would\n"
        "# hide the N-7 notice or breach WCAG 2.2.1. The API's /terms lives\n"
        "# at its root (SIG-API-013), outside the canonical origin's /v1/*\n"
        "# rule, so the target is the API's own base URL.\n"
        f"location = /terms {{ return 302 {base}/terms; }}\n"
        f"location = /terms/ {{ return 302 {base}/terms; }}\n"
    )


def render_release_conf(label: str, publication_id: str, conf_gen: str) -> str:
    """``conf/release_headers.conf`` — the §6.3 sig-web provenance pair
    (P35.13 / SIG-REL-009): ``X-SIG-Release: <label> <pub>`` and
    ``X-SIG-Conf-Gen: <n>`` on EVERY response — ``always`` so 4xx/5xx and
    tombstone answers carry them too, not only 200s. The values are the
    release's own (the descriptor's label + publication id) and the config
    generation the publish rolled — injected per activation like the other
    dark fragments, never rendered from live request state."""
    label = str(label or "").strip()
    pub = str(publication_id or "").strip()
    gen = str(conf_gen or "").strip()
    if not _LABEL_RE.fullmatch(label):
        raise ValueError(f"--release-label is not sig-YYYY-MM-DD.N: {label!r}")
    if not _PUB_RE.fullmatch(pub):
        raise ValueError(f"--release-pub is not p-<64hex>: {pub!r}")
    if not gen.isdigit():
        raise ValueError(f"--conf-gen must be a generation number, got {conf_gen!r}")
    return (
        "# P35.13 / SIG-REL-009 (G3 §6.3) — generated by `sig-ops web-conf`;\n"
        "# do not hand-edit. Lands under <bucket>/conf/ (a protected prefix).\n"
        "# Every sig-web response names the release it serves and the config\n"
        "# generation that rolled it — `always`, so error and tombstone\n"
        "# answers carry the same provenance.\n"
        f'add_header X-SIG-Release "{label} {pub}" always;\n'
        f"add_header X-SIG-Conf-Gen {gen} always;\n"
    )


def main(argv: list[str] | None = None) -> int:
    """``sig-ops web-conf --out-dir <staged>/conf [--api-base <url>]``."""
    parser = argparse.ArgumentParser(
        prog="sig-ops web-conf",
        description="D-P34.13-1 / P34.40 + P35.13: generate the dark conf/ "
        "fragments the sig-web nginx glob-includes — chrome_routes.conf "
        "(branded 403/410 + /task/→404) always; terms_redirect.conf (/terms → "
        "the API terms, a real 302) only when an API base is supplied; "
        "release_headers.conf (the §6.3 X-SIG-Release + X-SIG-Conf-Gen pair) "
        "only when label+pub+gen are all supplied.",
    )
    parser.add_argument(
        "--out-dir",
        required=True,
        help="the staged tree's conf/ dir (e.g. <staged>/conf)",
    )
    parser.add_argument(
        "--api-base",
        default=os.environ.get("SIG_API_BASE_URL"),
        help="the read-API base URL the /terms redirect targets "
        "(default: $SIG_API_BASE_URL; unset ⇒ no terms fragment)",
    )
    parser.add_argument(
        "--release-label",
        default=os.environ.get("SIG_LATEST_LABEL"),
        help="the active release's sig-YYYY-MM-DD.N label "
        "(default: $SIG_LATEST_LABEL; unset ⇒ no release-headers fragment)",
    )
    parser.add_argument(
        "--release-pub",
        default=os.environ.get("SIG_LATEST_PUB"),
        help="the active release's p-<64hex> publication id (default: $SIG_LATEST_PUB)",
    )
    parser.add_argument(
        "--conf-gen",
        default=os.environ.get("SIG_CONF_GEN"),
        help="the config generation number the publish rolled (default: $SIG_CONF_GEN)",
    )
    args = parser.parse_args(argv)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    chrome = out_dir / "chrome_routes.conf"
    chrome.write_text(render_chrome_conf(), encoding="utf-8")
    written.append(str(chrome))
    # The §6.3 provenance pair is all-or-nothing: a half-labelled revision
    # (release without gen, gen without release) is refused rather than
    # half-written.
    rel_args = (args.release_label, args.release_pub, args.conf_gen)
    if any(rel_args):
        if not all(rel_args):
            print(
                "web-conf: --release-label/--release-pub/--conf-gen are "
                "all-or-nothing — a half-labelled revision is refused",
                file=sys.stderr,
            )
            return 4
        release_conf = out_dir / "release_headers.conf"
        release_conf.write_text(
            render_release_conf(args.release_label, args.release_pub, args.conf_gen),
            encoding="utf-8",
        )
        written.append(str(release_conf))
    else:
        stale_rel = out_dir / "release_headers.conf"
        if stale_rel.exists():
            print(
                "web-conf: release headers unset but a release_headers.conf "
                "exists — refusing to leave a stale stamp (remove it "
                "deliberately)",
                file=sys.stderr,
            )
            return 4
    if args.api_base:
        terms = out_dir / "terms_redirect.conf"
        terms.write_text(render_terms_conf(args.api_base), encoding="utf-8")
        written.append(str(terms))
    else:
        stale = out_dir / "terms_redirect.conf"
        if stale.exists():
            print(
                "web-conf: --api-base unset but a terms_redirect.conf exists — "
                "refusing to leave a stale redirect (remove it deliberately)",
                file=sys.stderr,
            )
            return 4
    print(json.dumps({"wrote": written}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
