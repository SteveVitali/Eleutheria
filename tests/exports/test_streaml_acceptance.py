"""P37.67 (R11-CONF-14 / ADR-154) — the Stream-L acceptance record.

The committed ``exports/src/exports/data/streaml_acceptance.json`` is
GENERATED by ``scripts/eval/run_streaml_acceptance.py``; these tests pin the
committed bytes to a regeneration over the same inputs, assert the
fail-closed lint, and assert the honest posture: a flip lands only where its
named cause rows are landed, kept ratchets name their block, and no
criterion claims a release measurement the live leg never ran.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
ARTIFACT = REPO_ROOT / "exports" / "src" / "exports" / "data" / "streaml_acceptance.json"
sys.path.insert(0, str(REPO_ROOT / "scripts" / "eval"))

from exports.quality import load_registry  # noqa: E402
from exports.streaml_acceptance import (  # noqa: E402
    FLIP_TICKET,
    KEPT_RATCHET_REASONS,
    RERUN_PROMPT,
    SUCCESS_CRITERIA,
    acceptance_lint_errors,
)
from run_streaml_acceptance import build_doc  # noqa: E402

COMMITTED = json.loads(ARTIFACT.read_text(encoding="utf-8"))


def test_committed_record_matches_regeneration() -> None:
    """Committed == generated over the same inputs (the stamp is replayed so
    the comparison is byte-exact, never clock-dependent)."""
    regen = build_doc(generated_at=COMMITTED["generated_at"])
    assert regen == COMMITTED


def test_committed_record_lints_clean() -> None:
    assert acceptance_lint_errors(COMMITTED) == []


def test_every_registry_check_is_covered() -> None:
    registry_ids = {c.check_id for c in load_registry().checks}
    emitted = {c["id"] for c in COMMITTED["checks"]}
    assert emitted == registry_ids
    assert len(COMMITTED["checks"]) == len(registry_ids)


def test_flips_match_the_registry_and_their_causes_landed() -> None:
    """Every check carrying this row in ``fixing`` is enforce, every flipped
    row's other fixing rows are recorded landed, and the flip set is exactly
    the declared one."""
    registry = load_registry().by_id()
    flipped = {r["id"] for r in COMMITTED["checks"] if r["flip"] == "flipped"}
    assert set(COMMITTED["flips"]["flipped"]) == flipped
    assert flipped, "the CONF-14 tail sweep must flip at least one ratchet"
    landed = set(COMMITTED["landed_tickets"])
    for cid in flipped:
        check = registry[cid]
        assert check.mode == "enforce", cid
        assert FLIP_TICKET in check.fixing, cid
        causes = set(check.fixing) - {FLIP_TICKET}
        assert causes <= landed, f"{cid}: unlanded causes {causes - landed}"


def test_kept_ratchets_name_their_block() -> None:
    kept = {r["id"]: r for r in COMMITTED["checks"] if r["flip"] == "kept_ratchet"}
    assert kept == {r["id"]: r for r in COMMITTED["checks"] if r["mode"] == "ratchet"}
    for cid, row in kept.items():
        assert row["kept_reason"], cid
        assert cid in KEPT_RATCHET_REASONS, f"{cid} missing a committed reason"


def test_no_b3_b4_check_gates_and_no_b5_is_asserted() -> None:
    registry = load_registry().by_id()
    for row in COMMITTED["checks"]:
        check = registry[row["id"]]
        if check.mode in ("enforce", "ratchet"):
            assert check.basis_class in ("B0", "B1", "B2"), check.check_id
    for crit in COMMITTED["criteria"]:
        assert crit["basis"] != "B5"


def test_the_honest_posture_is_recorded() -> None:
    """The live leg is declared prepared_not_executed with the verbatim
    re-run prompt; no criterion may claim a release measurement."""
    m = COMMITTED["measurement"]
    assert m["live_leg"] == "prepared_not_executed"
    assert m["rerun_prompt"] == RERUN_PROMPT
    assert m["deferral"]
    for crit in COMMITTED["criteria"]:
        if crit["verdict"] == "not_measured":
            assert crit["deferral"], crit["id"]
        assert crit["basis"] in ("fixture", "engineered", "release", "")
    # The recorded before column is the L2 census, labelled historical.
    assert COMMITTED["l2"]["release"]
    assert COMMITTED["l2"]["metrics"] > 0


def test_criteria_cover_the_l3_section_9_list() -> None:
    emitted = {c["id"] for c in COMMITTED["criteria"]}
    assert emitted == {cid for cid, _text, _ev in SUCCESS_CRITERIA}
    texts = [c["text"] for c in COMMITTED["criteria"]]
    assert len(texts) == len(set(texts))


def test_lint_catches_a_fabricated_flip() -> None:
    """Fail-closed: a flip whose cause rows are not landed is a lint error,
    never a silent pass."""
    doc = json.loads(json.dumps(COMMITTED))
    flipped_row = next(c for c in doc["checks"] if c["flip"] == "flipped")
    flipped_row["fixing_landed"] = False
    errors = acceptance_lint_errors(doc)
    assert any("landed" in e for e in errors)


def test_lint_catches_a_silent_ratchet() -> None:
    doc = json.loads(json.dumps(COMMITTED))
    kept = next(c for c in doc["checks"] if c["flip"] == "kept_ratchet")
    kept["kept_reason"] = ""
    errors = acceptance_lint_errors(doc)
    assert any("kept" in e for e in errors)


def test_lint_catches_a_missing_criterion() -> None:
    doc = json.loads(json.dumps(COMMITTED))
    doc["criteria"] = doc["criteria"][:-1]
    doc["counts"]["criteria"] -= 1
    errors = acceptance_lint_errors(doc)
    assert any("criteria" in e for e in errors)


@pytest.mark.parametrize(
    "mut",
    [
        pytest.param(lambda d: d["measurement"].update(live_leg="ran"), id="live-claim"),
        pytest.param(lambda d: d["measurement"].update(rerun_prompt="make it up"), id="prompt"),
    ],
)
def test_lint_catches_dishonest_measurement_posture(mut) -> None:
    doc = json.loads(json.dumps(COMMITTED))
    mut(doc)
    assert acceptance_lint_errors(doc)
