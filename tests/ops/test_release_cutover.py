"""Fixture-verified tests for the P35.59 dark-cutover verb (REL-09, G3 §8.2/§11,
SIG-REL-004/005/006 + SIG-OPS-004 exercised).

The byte-identity contract the composed stack proves end-to-end in
``tests/e2e/test_release_cutover.py`` is built here piece by piece:

* ``cutover --label legacy-<date>`` composes genesis ``registry/conf/0/`` —
  an EMPTY promoted set (every gated namespace 404s, exactly what the flat
  site answers for a not-published release route), the floor's own live
  ``conf/withdrawn_*.conf`` + ``conf/selectors*.conf`` carried VERBATIM
  (the flat barrier is the truth the leg must reproduce — never a
  re-derived map), a floor-pointer ``latest.json`` (``publication_id``
  ``None``, never a pub id), and **no** ``releases/`` index set — the flat
  site 404s ``/releases/`` today, so writing the index would be the one
  visible change the leg forbids;
* the floor's whole ``conf/`` subtree carries verbatim to ``staged/conf/``
  (the template's chrome/terms/renamed globs + the tombstone bodies the
  carried deny map's ``error_page 410`` targets resolve);
* ``registry/serving.json`` retires the legacy bucket-root publish class —
  the declaration ``sig-ops publish-web --apply`` refuses on;
* the verb refuses a pub-shaped label, an unimported floor, a second
  genesis (``conf/<gen>`` present), a non-digest ``--web-image``, and an
  ``--apply`` without a ``--go`` authority record;
* the roll is recorded intent (env triple + mount + digest), never a live
  mutation the verb performs.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pytest

from ops import release_conf as rc
from ops import release_pipeline as rp
from ops import release_reversal as rr

NOW = datetime(2026, 10, 26, 15, 0, 0, tzinfo=UTC)

LABEL = "legacy-20261024"
DIGEST_WEB = "gcr.io/sig/sig-web@sha256:" + "2" * 64

WITHDRAWN_LIVE = (
    b"# Generated by the SIG release tooling - withdrawn release routes (P34.41).\n"
    b"location = /visual-language/ { error_page 410 /conf/tombstone/dead.html; "
    b"return 410; }\n"
)
CHROME_LIVE = b"error_page 403 /403.html;\nerror_page 410 /410.html;\n"
TERMS_LIVE = b"location = /terms { return 302 /v1/terms; }\n"
TOMBSTONE_LIVE = b"<html><body>tombstone fixture</body></html>"


def _store(tmp_path: Path) -> rp.LocalDirStore:
    return rp.LocalDirStore(tmp_path / "reg")


def _legacy_tree(tmp_path: Path) -> Path:
    """A then-live flat tree: site pages, the generated conf/ fragments the
    legacy nginx includes, one tombstone body, and one denied-into page."""
    src = tmp_path / "live"
    (src / "dossier" / "x").mkdir(parents=True)
    (src / "conf" / "tombstone").mkdir(parents=True)
    (src / "entity" / "t" / "e1").mkdir(parents=True)
    (src / "index.html").write_text("<html>live root</html>", encoding="utf-8")
    (src / "404.html").write_text("<html>not found</html>", encoding="utf-8")
    (src / "dossier" / "x" / "index.html").write_text("<html>dossier x</html>")
    (src / "entity" / "t" / "e1" / "index.html").write_text("<html>stub e1</html>")
    (src / "conf" / "withdrawn_routes.conf").write_bytes(WITHDRAWN_LIVE)
    (src / "conf" / "chrome_errors.conf").write_bytes(CHROME_LIVE)
    (src / "conf" / "terms_redirect.conf").write_bytes(TERMS_LIVE)
    (src / "conf" / "tombstone" / "dead.html").write_bytes(TOMBSTONE_LIVE)
    return src


def _authority(store: rp.Store, name: str = "go-1", **fields: Any) -> dict[str, Any]:
    rec = {
        "schema": rr.AUTHORITY_SCHEMA,
        "kind": "go",
        "ref": f"OPS-{name}",
        "issued_at": "2026-10-23T00:00:00Z",
        **fields,
    }
    body = json.dumps(rec, sort_keys=True).encode()
    if store.stat(f"{rr.AUTHORITIES_PREFIX}{name}") is None:
        store.insert(f"{rr.AUTHORITIES_PREFIX}{name}", body)
    return rec


def _imported_floor(store: rp.Store, tmp_path: Path, label: str = LABEL) -> Path:
    src = _legacy_tree(tmp_path)
    _authority(store)
    rr.verb_import_floor(store, apply_=True, source_dir=src, label=label, go="go-1", now=NOW)
    return src


