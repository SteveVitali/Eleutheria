def test_cutover_composes_gen0_for_byte_identity(tmp_path: Path) -> None:
    store = _store(tmp_path)
    _imported_floor(store, tmp_path)
    out = rr.verb_cutover(store, apply_=True, label=LABEL, go="go-1", web_image=DIGEST_WEB, now=NOW)
    assert out["applied"] is True and out["conf_gen"] == 0
    # latest.json is the floor pointer — a label, never a publication id.
    latest = rc.read_generation(store, 0)
    assert latest["publication_id"] is None
    assert latest["legacy_floor"] == LABEL and latest["label"] == LABEL
    assert latest["conf_gen"] == 0 and latest["cutover"] is True
    assert not rc.PUB_RE.match(LABEL)
    # the genesis promoted set is empty — /r/, /s/, /releases/<pub> 404 by
    # construction, identical to the flat site for a not-published route.
    assert rc.read_promoted_map(store, 0) == set()
    # the live deny barrier + fragments carry VERBATIM — never re-derived.
    assert store.read("registry/conf/0/withdrawn.conf") == WITHDRAWN_LIVE
    # no selectors on the flat tree → the empty placeholder, not a guess.
    sel = store.read("registry/conf/0/selectors.conf")
    assert sel is not None and b"location" not in sel
    # NO releases/ index set — /releases/ stays the denied route it is today.
    assert store.list("registry/conf/0/releases/") == []
    # the staged fragment carry: every floor conf/ object lands verbatim.
    assert store.read("staged/conf/withdrawn_routes.conf") == WITHDRAWN_LIVE
    assert store.read("staged/conf/chrome_errors.conf") == CHROME_LIVE
    assert store.read("staged/conf/terms_redirect.conf") == TERMS_LIVE
    assert store.read("staged/conf/tombstone/dead.html") == TOMBSTONE_LIVE
    # the retirement record — the publish guard's truth.
    serving = rr.serving_layout(store)
    assert serving is not None
    assert serving["schema"] == rr.SERVING_SCHEMA
    assert serving["legacy_publish_class"] == "retired"
    assert serving["floor"] == LABEL
    # the roll is recorded intent — env triple + digest, status prepared.
    roll = out["roll"]
    assert roll["status"] == "prepared" and roll["image"] == DIGEST_WEB
    assert roll["env"] == {
        "SIG_CONF_GEN": "0",
        "SIG_LATEST_PUB": LABEL,
        "SIG_LATEST_LABEL": LABEL,
        "SIG_STAGING": "0",
    }
    assert roll["min_instances"] == 1
    # every post-check passes; the journal carries the cutover event.
    assert all(c["status"] == "pass" for c in out["checks"])
    assert "legacy-cutover" in {e["verb"] for e in rp.list_events(store)}


def test_cutover_dry_run_writes_nothing(tmp_path: Path) -> None:
    store = _store(tmp_path)
    _imported_floor(store, tmp_path)
    out = rr.verb_cutover(store, apply_=False, label=LABEL, go="go-1", now=NOW)
    assert out["dry_run"] is True
    assert store.list("registry/conf/0/") == []
    assert store.list("staged/conf/") == []
    assert rr.serving_layout(store) is None


def test_cutover_is_idempotent_under_create_if_absent(tmp_path: Path) -> None:
    store = _store(tmp_path)
    _imported_floor(store, tmp_path)
    rr.verb_cutover(store, apply_=True, label=LABEL, go="go-1", now=NOW)
    second = rr.verb_cutover(store, apply_=True, label=LABEL, go="go-1", now=NOW)
    assert second["applied"] is True
    assert second["written"] == []  # every object carried — a resume, not a rewrite
    assert sorted(second["carried_unchanged"]) == sorted(
        f"registry/conf/0/{rel}" for rel in first_files()
    )


def first_files() -> list[str]:
    return ["promoted.map", "latest.json", "withdrawn.conf", "selectors.conf", "labels.conf"]


def test_cutover_refuses_an_unimported_floor(tmp_path: Path) -> None:
    store = _store(tmp_path)
    _authority(store)
    with pytest.raises(rp.PipelineError, match="not an imported legacy floor"):
        rr.verb_cutover(store, apply_=True, label=LABEL, go="go-1", now=NOW)


def test_cutover_refuses_a_pub_shaped_label(tmp_path: Path) -> None:
    store = _store(tmp_path)
    with pytest.raises(rp.PipelineError, match="never a p-<64hex> publication id"):
        rr.verb_cutover(store, apply_=False, label="p-" + "a" * 64, go="go-1", now=NOW)


def test_cutover_refuses_a_second_genesis(tmp_path: Path) -> None:
    store = _store(tmp_path)
    _imported_floor(store, tmp_path)
    rr.verb_cutover(store, apply_=True, label=LABEL, go="go-1", now=NOW)
    # a later generation exists (a real promote) — genesis may not be re-cut.
    store.insert(
        "registry/conf/1/latest.json",
        json.dumps({"schema": rc.LATEST_SCHEMA_V2, "publication_id": "p-" + "a" * 64}).encode(),
    )
    with pytest.raises(rp.PipelineError, match="never a second genesis"):
        rr.verb_cutover(store, apply_=True, label=LABEL, go="go-1", now=NOW)


def test_cutover_refuses_a_non_digest_image(tmp_path: Path) -> None:
    store = _store(tmp_path)
    _imported_floor(store, tmp_path)
    with pytest.raises(rp.PipelineError, match="not a digest-pinned ref"):
        rr.verb_cutover(
            store,
            apply_=True,
            label=LABEL,
            go="go-1",
            web_image="gcr.io/sig/sig-web:latest",
            now=NOW,
        )


def test_cutover_apply_requires_a_go_record(tmp_path: Path) -> None:
    store = _store(tmp_path)
    _imported_floor(store, tmp_path)
    with pytest.raises(rp.PipelineError, match="needs --go"):
        rr.verb_cutover(store, apply_=True, label=LABEL, now=NOW)


def test_cutover_seeds_the_withdrawal_registry_verbatim(tmp_path: Path) -> None:
    store = _store(tmp_path)
    _imported_floor(store, tmp_path)
    doc = {
        "schema": "sig.withdrawal-registry/1",
        "entries": [{"target_kind": "entity", "target_id": "e-old"}],
    }
    wf = tmp_path / "withdrawals.json"
    wf.write_text(json.dumps(doc, sort_keys=True))
    out = rr.verb_cutover(store, apply_=True, label=LABEL, go="go-1", withdrawals=wf, now=NOW)
    assert out["applied"] is True
    assert store.read("registry/withdrawals.json") == wf.read_bytes()


def test_cutover_refuses_a_non_registry_withdrawals_seed(tmp_path: Path) -> None:
    store = _store(tmp_path)
    _imported_floor(store, tmp_path)
    bad = tmp_path / "not-a-registry.json"
    bad.write_text(json.dumps({"schema": "sig.other/1"}))
    with pytest.raises(rp.PipelineError, match="not a sig.withdrawal-registry"):
        rr.verb_cutover(store, apply_=True, label=LABEL, go="go-1", withdrawals=bad, now=NOW)


