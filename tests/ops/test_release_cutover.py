def test_serving_layout_is_none_precutover_and_the_doc_after(tmp_path: Path) -> None:
    store = _store(tmp_path)
    assert rr.serving_layout(store) is None
    _imported_floor(store, tmp_path)
    rr.verb_cutover(store, apply_=True, label=LABEL, go="go-1", now=NOW)
    doc = rr.serving_layout(store)
    assert doc is not None and doc["layout"] == "release"
    assert doc["legacy_bucket"]["retention_days"] == 90
