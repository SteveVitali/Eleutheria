def _docker_reachable() -> bool:
    try:
        import docker

        docker.from_env().ping()
        return True
    except Exception:
        return False


if not _docker_reachable() and not os.environ.get("SIG_REQUIRE_DB_TESTS"):
    pytest.skip(
        "Docker daemon not reachable; composed cutover tests skip (P35.59)",
        allow_module_level=True,
    )


def _compose(*args: str, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    e = dict(os.environ)
    if env:
        e.update(env)
    return subprocess.run(
        ["docker", "compose", "-p", COMPOSE_PROJECT, "-f", str(COMPOSE_FILE), *args],
        capture_output=True,
        text=True,
        check=False,
        env=e,
        cwd=str(REPO_ROOT / "ops"),
    )


def _http(url: str) -> tuple[int, dict[str, str], bytes]:
    req = urllib.request.Request(url)
    try:
        with urllib.request.urlopen(req, timeout=15) as r:  # noqa: S310 — loopback only
            return r.status, dict(r.headers), r.read()
    except urllib.error.HTTPError as e:
        return e.code, dict(e.headers), e.read()


def _container_state() -> str:
    out = []
    for name in (f"{COMPOSE_PROJECT}-web-1",):
        logs = subprocess.run(
            ["docker", "logs", "--tail", "60", name],
            capture_output=True,
            text=True,
            check=False,
        )
        out.append(f"--- docker logs {name} ---\n{logs.stdout}{logs.stderr}")
    return "\n".join(out)


def _wait_for(url: str, timeout_s: int = 300, want_status: int = 200) -> None:
    deadline = time.monotonic() + timeout_s
    last_status: int | None = None
    while time.monotonic() < deadline:
        try:
            status, _h, _b = _http(url)
            last_status = status
            if status == want_status:
                return
        except (urllib.error.URLError, OSError):
            pass
        time.sleep(2)
    raise AssertionError(
        f"{url} never answered {want_status} within {timeout_s}s "
        f"(last_status={last_status})\n{_container_state()}"
    )


def _legacy_tree(src: Path) -> None:
    """The then-live flat tree the leg snapshots: allow-listed pages, the
    generated conf/ fragment surface (the REAL web-conf renderers), one
    carried deny line + its tombstone body, and the release namespaces the
    flat bucket also carries."""
    (src / "dossier" / "x").mkdir(parents=True)
    (src / "conf" / "tombstone").mkdir(parents=True)
    (src / "entity" / "t" / "e1").mkdir(parents=True)
    (src / "_astro").mkdir(parents=True)
    (src / "r" / ("p-" + "a" * 64)).mkdir(parents=True)
    (src / "index.html").write_bytes(INDEX_BODY)
    (src / "404.html").write_bytes(NOTFOUND_BODY)
    (src / "403.html").write_bytes(b"<html>branded 403 - fixture</html>")
    (src / "410.html").write_bytes(b"<html>branded 410 - fixture</html>")
    (src / "dossier" / "x" / "index.html").write_bytes(DOSSIER_BODY)
    (src / "entity" / "t" / "e1" / "index.html").write_bytes(STUB_BODY)
    (src / "_astro" / "app.css").write_bytes(b"body{color:#000}")
    (src / "r" / ("p-" + "a" * 64) / "index.html").write_bytes(b"<html>records</html>")
    (src / "conf" / "withdrawn_routes.conf").write_bytes(WITHDRAWN_LIVE)
    (src / "conf" / "chrome_routes.conf").write_text(web_conf.render_chrome_conf())
    (src / "conf" / "terms_redirect.conf").write_text(
        web_conf.render_terms_conf("https://api.example.test")
    )
    (src / "conf" / "tombstone" / "dead.html").write_bytes(TOMBSTONE_BODY)


@pytest.fixture(scope="module")
def cutover_root(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """The /mnt/rel root the container serves — the real import-floor +
    cutover verbs compose it over a LocalDirStore."""
    root = tmp_path_factory.mktemp("cutover-root")
    # See test_release_generations: a native-Linux nginx worker cannot
    # traverse a 0700 foreign-owned mkdtemp — the bind-mount fixture is
    # 0755 like the real bucket mount.
    root.chmod(0o755)
    src = tmp_path_factory.mktemp("legacy-src")
    _legacy_tree(src)
    store = rp.LocalDirStore(root)
    (root / "registry" / "authorities").mkdir(parents=True)
    (root / "registry" / "authorities" / "go").write_bytes(
        json.dumps(
            {
                "schema": rr.AUTHORITY_SCHEMA,
                "kind": "go",
                "ref": "GATE-G4 OM-20 list — P35.59 named",
                "issued_at": "2026-10-09T17:32:00Z",
            }
        ).encode()
    )
    imp = rr.verb_import_floor(store, apply_=True, source_dir=src, label=LABEL, go="go", now=NOW)
    assert imp["applied"] is True
    out = rr.verb_cutover(store, apply_=True, label=LABEL, go="go", now=NOW)
    assert out["applied"] is True
    assert all(c["status"] == "pass" for c in out["checks"]), out["checks"]
    up = _compose(
        "--profile",
        "release-serving",
        "up",
        "-d",
        "--build",
        "web",
        env={
            "SIG_CONF_GEN": "0",
            "SIG_LATEST_PUB": LABEL,
            "SIG_LATEST_LABEL": LABEL,
            "SIG_RELEASE_ROOT": str(root),
            "SIG_WEB_PORT": str(WEB_PORT),
        },
    )
    assert up.returncode == 0, f"compose up failed:\n{up.stdout}\n{up.stderr}"
    _wait_for(f"{WEB}/", want_status=200)
    yield root
    _compose("--profile", "release-serving", "down", "-v")


def test_floor_routes_serve_byte_identical_through_the_template(cutover_root: Path):
    for route, body in (
        ("/", INDEX_BODY),
        ("/index.html", INDEX_BODY),
        ("/dossier/x/", DOSSIER_BODY),
        ("/entity/t/e1/", STUB_BODY),
        ("/_astro/app.css", b"body{color:#000}"),
    ):
        status, _h, got = _http(f"{WEB}{route}")
        assert (status, got) == (200, body), f"{route}: {status} {got!r}"


def test_the_carried_deny_answers_410_with_its_tombstone(cutover_root: Path):
    status, headers, body = _http(f"{WEB}{DENIED_ROUTE}")
    assert status == 410 and body == TOMBSTONE_BODY
    assert headers.get("X-SIG-Conf-Gen") == "0"


def test_the_carried_fragments_wire_unchanged(cutover_root: Path):
    # chrome: the bare /task/ prefix answers a plain 404 — never the bucket 403.
    status, _h, body = _http(f"{WEB}/task/")
    assert status == 404 and body == NOTFOUND_BODY
    # terms: the real 302 fragment, unchanged.
    conn_status, conn_loc = _redirect(f"{WEB}/terms")
    assert conn_status == 302 and conn_loc == "https://api.example.test/terms"
    # the tombstone body files stay internal — never a fetchable route.
    status, _h, _b = _http(f"{WEB}/conf/tombstone/dead.html")
    assert status == 404


def _redirect(url: str) -> tuple[int, str | None]:
    import http.client

    conn = http.client.HTTPConnection("127.0.0.1", WEB_PORT, timeout=15)
    conn.request("GET", url)
    resp = conn.getresponse()
    resp.read()
    return resp.status, resp.getheader("Location")


def test_unpromoted_and_denied_namespaces_stay_denied(cutover_root: Path):
    # The genesis promoted set is empty: the release namespaces answer the
    # same 404 the flat site gives a not-published route — and /releases/
    # stays the denied route conf/0 deliberately does not write.
    for route in (f"/r/{'p-' + 'a' * 64}/", "/releases/", "/releases/index.html", "/s/"):
        status, _h, _b = _http(f"{WEB}{route}")
        assert status == 404, f"{route} → {status}"


def test_the_provenance_pair_rides_every_response(cutover_root: Path):
    for route in ("/", DENIED_ROUTE, "/missing/"):
        _status, headers, _b = _http(f"{WEB}{route}")
        assert headers.get("X-SIG-Release") == f"{LABEL} {LABEL}"
        assert headers.get("X-SIG-Conf-Gen") == "0"


def test_conf0_carries_no_releases_index(cutover_root: Path):
    assert not list((cutover_root / "registry" / "conf" / "0").glob("releases/*"))
    serving = json.loads((cutover_root / "registry" / "serving.json").read_text())
    assert serving["schema"] == rr.SERVING_SCHEMA
    assert serving["legacy_publish_class"] == "retired"
    assert rc.read_generation(rp.LocalDirStore(cutover_root), 0)["legacy_floor"] == LABEL
