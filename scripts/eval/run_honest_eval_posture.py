"""Reproducible generator for the P34.45 honest-evaluation posture report
(ADR-152/153; the report the ticket commits under ``docs/build/reports/``).

Runs the design-aware evaluator over the *committed* camera gold set framed
honestly: every label is agent-provenance (the ``verifier`` is an
agent-maintainer seed; the ``llm`` adjudicator is reported as diagnostics).
The output states what Round 11 actually has — every human estimand
``unavailable`` with its reason, every figure carrying its basis class —
instead of substituting agent/LLM agreement for human ground truth.

Deterministic — re-run to regenerate the exact report.

Run:  uv run python scripts/eval/run_honest_eval_posture.py
"""

from __future__ import annotations

import json
from pathlib import Path

from resolution.evaluator import (
    EvalUnit,
    HypothesisSpec,
    SamplingDesign,
    StratumSpec,
    evaluate,
    render_report_md,
    report_digest,
)

REPO = Path(__file__).resolve().parents[2]
GOLD = REPO / "resolution/src/resolution/data/camera_site_gold.json"
OUT = REPO / "docs/build/reports/2026-10-09_honest_evaluation_posture.md"

#: The agent label vocabulary in the committed gold → reference outcomes.
_OUTCOME = {
    "match": "same",
    "non_match": "different",
    "not_enough_information": "insufficient_evidence",
}

TIERS = (1, 3, 4, 5)


def main() -> None:
    gold = json.loads(GOLD.read_text(encoding="utf-8"))
    frozen = [p for p in gold["pairs"] if p.get("frozen")]

    # The honest frame: every frozen-holdout pair is one auto_positive_precision
    # unit whose reference label is AGENT-provenance — never human. The pair_id
    # is its own dependency group (no correlated draws).
    units: list[EvalUnit] = []
    for p in frozen:
        agent = next(a for a in p["adjudications"] if a["adjudicator"].startswith("agent:"))
        units.append(
            EvalUnit(
                sample_id=p["pair_id"],
                estimand="auto_positive_precision",
                stratum_id="holdout",
                partition="pilot",
                dependency_group_id=p["pair_id"],
                outcome=_OUTCOME[agent["label"]],
                reference_provenance="agent",
                tier=p["snapshot"]["sampled_at_tier"],
                scope="snapshot",
            )
        )

    design = SamplingDesign(
        design_id="p34.45-honest-posture",
        kind="stratified_srs",
        equal_probability=True,
        independent_unit="item",
        independence_basis=(
            "one frozen-holdout pair per dependency group; the agent-labelled "
            "frame is reported under basis `agent` — it can never certify a "
            "human estimand"
        ),
        family_alpha=0.05,
        hypotheses=tuple(
            HypothesisSpec(
                tier=t,
                scope="snapshot",
                alpha=0.05 / len(TIERS),
                threshold=0.98,
                cells=(StratumSpec("holdout", population=len(frozen)),),
            )
            for t in TIERS
        ),
        target_population="frozen camera-site gold holdout (agent-labelled)",
        frame_digest=f"camera_site_gold.json:{gold['version']}",
        ruleset_digest=gold["rules_version"],
    )

    report = evaluate(
        units=units,
        design=design,
        notes=(
            "The committed camera gold set's provenance is `agent` "
            "(verifier: an agent-maintainer seed; the llm adjudicator is a "
            "fresh-context run of the same model family). No independent "
            "human evaluation exists in Round 11 — every human estimand is "
            "therefore `unavailable`, reported never substituted.",
            "Under ruleset v3-interim (ADR-153) inferential tiers [3,4,5] are "
            "review-only: this report attaches to P35.63's Class S readout "
            "and publishes nothing itself.",
        ),
    )

    header = [
        "<!-- GENERATED by scripts/eval/run_honest_eval_posture.py — "
        "deterministic; re-run to regenerate. -->",
        "",
        "<!-- P34.45 honest-evaluation posture report (ADR-152/153).",
        "     Every human estimand is `unavailable`: the only reference labels",
        "     that exist are agent-provenance, and agent/LLM labels can never",
        "     measure a human estimand. -->",
        "",
    ]
    footer = [
        "",
        "---",
        "",
        f"report digest: `{report_digest(report)}` · generated `date -u` "
        "2026-10-09 · attaches to P35.63's Class S readout (publishes nothing)",
    ]
    OUT.write_text(
        "\n".join(header) + render_report_md(report) + "\n".join(footer) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(REPO)}")
    for name, est in sorted(report.estimands.items()):
        print(f"  {name}: {est.state} (basis={est.basis}, reason={est.unavailable_reason})")


if __name__ == "__main__":
    main()
